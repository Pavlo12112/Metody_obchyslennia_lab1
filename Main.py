# =========================================================
# 2. Обчислення відстані між двома GPS-точками
# =========================================================

def haversine(lat1, lon1, lat2, lon2):

    # Ця функція знаходить відстань між двома GPS-точками.
    #
    # На вході:
    # lat1, lon1 - координати першої точки
    # lat2, lon2 - координати другої точки
    #
    # На виході отримуємо відстань у метрах.

    # Приблизний радіус Землі в метрах.
    R = 6371000

    # GPS-координати спочатку задані в градусах.
    # Для математичних функцій переводимо їх у радіани.
    p1 = np.radians(lat1)
    p2 = np.radians(lat2)

    # Знаходимо різницю між широтами та довготами
    # і також переводимо її в радіани.
    dp = np.radians(lat2 - lat1)
    dl = np.radians(lon2 - lon1)

    # Це основна частина формули Haversine.
    # Вона враховує, що Земля має приблизно сферичну форму.
    a = (
        np.sin(dp / 2) ** 2
        + np.cos(p1) * np.cos(p2)
        * np.sin(dl / 2) ** 2
    )

    # Отримуємо кінцеву відстань між двома точками.
    # Результат буде в метрах.
    return 2 * R * np.arctan2(
        np.sqrt(a),
        np.sqrt(1 - a)
    )


