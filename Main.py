# 9. Вибір потрібної кількості вузлів
# =========================================================

def subsample(count):

    # Тут ми беремо не всі 21 точки,
    # а потрібну кількість точок.
    #
    # Наприклад:
    # count = 10 -> беремо 10 вузлів
    # count = 15 -> беремо 15 вузлів
    # count = 20 -> беремо 20 вузлів

    # Рівномірно вибираємо індекси
    # від першої до останньої точки.
    #
    # Тобто ми не беремо просто перші 10,
    # а намагаємося рівномірно розподілити
    # вибрані вузли вздовж усього маршруту.
    idx = np.unique(
        np.linspace(
            0,
            len(distances) - 1,
            count
        ).astype(int)
    )

    # Повертаємо відстані та висоти
    # вибраних вузлів.
    return (
        distances[idx],
        elevations[idx]
    )


