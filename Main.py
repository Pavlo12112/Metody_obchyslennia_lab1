    # Наприклад:
    # еталон = 1000 м
    # наш сплайн = 997 м
    # похибка = 3 м
    error = np.abs(
        yy - reference
    )

    # Виводимо:
    # найбільшу похибку
    # і середню похибку.
    print(
        f"{count} вузлів: "
        f"max = {np.max(error):.3f} м, "
        f"середня = {np.mean(error):.3f} м"
    )


