# =========================================================
# 6. Функція побудови природного кубічного сплайна
# =========================================================

def spline_coeffs(x, y):

    # Тут ми будуємо кубічний сплайн.
    #
    # x - відстані між вузлами
    # y - висоти у цих вузлах
    #
    # Функція повинна знайти коефіцієнти
    # для кожної ділянки сплайна.

    # Кількість відрізків на один менша
    # за кількість вузлів.
    #
    # Наприклад:
    # 21 вузол -> 20 відрізків.
    n = len(x) - 1

    # h показує довжину кожного відрізка
    # між сусідніми вузлами.
    h = np.diff(x)

    # Створюємо масив для допоміжних обчислень.
    alpha = np.zeros(n + 1)

    # Обчислюємо alpha для внутрішніх вузлів.
    #
    # Ці значення потрібні для побудови
    # системи рівнянь кубічного сплайна.
    for i in range(1, n):
        alpha[i] = (
            3 * (y[i + 1] - y[i]) / h[i]
            - 3 * (y[i] - y[i - 1]) / h[i - 1]
        )

    # Створюємо допоміжні масиви.
    #
    # Вони використовуються під час розв'язання
    # системи рівнянь методом прогонки.
    l = np.zeros(n + 1)
    mu = np.zeros(n + 1)
    z = np.zeros(n + 1)

    # Перша гранична умова природного сплайна.
    l[0] = 1

    # Прямий хід методу прогонки.
    #
    # Тут поступово обчислюємо допоміжні
    # коефіцієнти для внутрішніх вузлів.
    for i in range(1, n):

        l[i] = (
            2 * (x[i + 1] - x[i - 1])
            - h[i - 1] * mu[i - 1]
        )

        mu[i] = h[i] / l[i]

        z[i] = (
            alpha[i]
            - h[i - 1] * z[i - 1]
        ) / l[i]

    # Друга гранична умова природного сплайна.
    #
    # Для природного сплайна друга похідна
    # на кінцях дорівнює нулю.
    l[n] = 1
    z[n] = 0

    # Створюємо масиви коефіцієнтів сплайна.
    c = np.zeros(n + 1)
    b = np.zeros(n)
    d = np.zeros(n)

    # Коефіцієнт "a" — це значення висоти
    # у лівій точці кожного відрізка.
    a = y[:n].copy()

    # Зворотний хід методу прогонки.
    #
    # Тут після прямого ходу знаходимо
    # остаточні коефіцієнти сплайна.
    for j in range(n - 1, -1, -1):

        c[j] = z[j] - mu[j] * c[j + 1]

        b[j] = (
            (y[j + 1] - y[j]) / h[j]
            - h[j] * (c[j + 1] + 2 * c[j]) / 3
        )

        d[j] = (
            c[j + 1] - c[j]
        ) / (3 * h[j])

    # Повертаємо чотири коефіцієнти:
    # a, b, c, d.
    #
    # За ними потім можна обчислити
    # значення сплайна в будь-якій точці.
    return a, b, c[:n], d


# =========================================================
# 7. Функція обчислення значення сплайна
# =========================================================

def spline(x, a, b, c, d, values):

    # Ця функція вже не будує сплайн,
    # а обчислює його значення.
    #
    # Тобто ми маємо коефіцієнти
    # і хочемо дізнатися:
    #
    # "Яка висота сплайна ось у цій точці?"

    # Перетворюємо значення в NumPy-масив.
    values = np.atleast_1d(values)

    # Створюємо масив для результатів.
    result = np.zeros_like(
        values,
        dtype=float
    )

    # Перебираємо всі точки,
    # де потрібно знайти значення сплайна.
    for k, value in enumerate(values):

        # Знаходимо, між якими двома вузлами
        # знаходиться поточна точка.
        i = np.searchsorted(x, value) - 1

        # Перевіряємо, щоб номер відрізка
        # не вийшов за межі масиву.
        i = max(
            0,
            min(i, len(a) - 1)
        )

        # dx — відстань від лівого вузла
        # поточного відрізка.
        dx = value - x[i]

        # Тут використовується формула
        # кубічного полінома.
        #
        # S(x) =
        # a + b*dx + c*dx² + d*dx³
        #
        # Саме тому сплайн називається кубічним.
        result[k] = (
            a[i]
            + b[i] * dx
            + c[i] * dx**2
            + d[i] * dx**3
        )

    # Повертаємо отримані значення.
    return result


